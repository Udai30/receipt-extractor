"""The Gradio Blocks app: Results · Try it · Failures · About (UI_UX_DESIGN §1, FR-8).

Importing this module imports Gradio (heavy); the package imports it only when the app is
built. Callbacks only move values between components and the Gradio-free modules
(``reports``, ``showcase``, ``live``, ``presenters``). Hardening (TRD §S7):

- queue: 2 concurrent jobs, 20 waiting; Gradio's own upload limit 5 MB plus server-side checks;
- uploads arrive as a Gradio temp file, which is read into memory and **deleted at once**
  (``delete_cache`` sweeps anything left); nothing is logged but metadata;
- uploads go to pipeline A only; samples are cached results (B never runs live here);
- analytics off; errors are plain language with a request id.
"""

