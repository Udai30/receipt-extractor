"""SQLAlchemy 2 typed models for the shared tables (BACKEND_SCHEMA §S1-§S2).

Conventions (BACKEND_SCHEMA §S1): ``uuid`` primary keys generated by the server with
``gen_random_uuid()``, ``created_at timestamptz not null default now()`` on every table,
enumerations as ``text`` + ``CHECK``, JSON payloads as ``jsonb``.

The baseline Alembic revision (``migrations/versions/0001_baseline.py``) must create exactly
this schema; ``tests/integration/test_migrations.py`` compares the two.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any, Final

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Double,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    Numeric,
    SmallInteger,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint/index names so Alembic revisions are reproducible.
NAMING_CONVENTION: Final = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

EVAL_RUN_STATUSES: Final = ("completed", "partial", "failed")
EVAL_RESULT_STATUSES: Final = ("pass", "fail", "error")


def _in_check(column: str, values: tuple[str, ...]) -> str:
    allowed = ", ".join(f"'{value}'" for value in values)
    return f"{column} IN ({allowed})"


class Base(DeclarativeBase):
    """Declarative base: shared metadata, ``id`` and ``created_at`` columns."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Fetch server-generated id/created_at with INSERT ... RETURNING, so no lazy load
    # (which would be implicit I/O under asyncio) is needed after a flush.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012 - SQLAlchemy reads a plain dict

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


class EvalRun(Base):
    """One evaluation run of a pipeline variant over a dataset sample."""

    __tablename__ = "eval_run"
    __table_args__ = (CheckConstraint(_in_check("status", EVAL_RUN_STATUSES), name="status"),)

    run_key: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    name: Mapped[str] = mapped_column(Text, nullable=False)
    variant: Mapped[str] = mapped_column(Text, nullable=False)
    config: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    dataset_split: Mapped[str] = mapped_column(Text, nullable=False)
    dataset_hash: Mapped[str] = mapped_column(Text, nullable=False)
    sample_size: Mapped[int] = mapped_column(Integer, nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False)
    metrics: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    latency_p50_ms: Mapped[int | None] = mapped_column(Integer)
    latency_p95_ms: Mapped[int | None] = mapped_column(Integer)
    tokens_in: Mapped[int | None] = mapped_column(BigInteger)
    tokens_out: Mapped[int | None] = mapped_column(BigInteger)
    list_cost_usd: Mapped[Decimal | None] = mapped_column(Numeric(12, 6))
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class EvalResult(Base):
    """Per-case outcome of an :class:`EvalRun`; deleted together with its run."""

    __tablename__ = "eval_result"
    # The FK on run_id is covered by both composite indexes (run_id is the leading column),
    # so no separate single-column index is needed (BACKEND_SCHEMA §S1).
    __table_args__ = (
        CheckConstraint(_in_check("status", EVAL_RESULT_STATUSES), name="status"),
        UniqueConstraint("run_id", "case_id"),
        Index("ix_eval_result_run_id_status", "run_id", "status"),
    )

    run_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("eval_run.id", ondelete="CASCADE"), nullable=False
    )
    case_id: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False)
    score: Mapped[float | None] = mapped_column(Double)
    prediction: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    gold: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    details: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, default=dict, server_default=text("'{}'::jsonb")
    )
    latency_ms: Mapped[int | None] = mapped_column(Integer)
    failure_label: Mapped[str | None] = mapped_column(Text)
    failure_note: Mapped[str | None] = mapped_column(Text)


class LLMCall(Base):
    """Accounting record of one model call (TRD §S3); ``run_id`` is null for live traffic.

    The FK does not cascade (BACKEND_SCHEMA §S1: deletes cascade only from a run to its own
    results), so a run that still has llm_call rows cannot be deleted by accident.
    """

    __tablename__ = "llm_call"
    __table_args__ = (
        Index("ix_llm_call_run_id", "run_id"),
        Index("ix_llm_call_created_at", "created_at"),
    )

    run_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("eval_run.id"))
    request_id: Mapped[str | None] = mapped_column(Text)
    case_id: Mapped[str | None] = mapped_column(Text)
    stage: Mapped[str | None] = mapped_column(Text)
    provider: Mapped[str] = mapped_column(Text, nullable=False)
    model: Mapped[str] = mapped_column(Text, nullable=False)
    tokens_in: Mapped[int | None] = mapped_column(Integer)
    tokens_out: Mapped[int | None] = mapped_column(Integer)
    latency_ms: Mapped[int] = mapped_column(Integer, nullable=False)
    cache_hit: Mapped[bool] = mapped_column(nullable=False)
    retries: Mapped[int] = mapped_column(
        SmallInteger, nullable=False, default=0, server_default=text("0")
    )
    schema_valid: Mapped[bool | None] = mapped_column()
    list_cost_usd: Mapped[Decimal | None] = mapped_column(Numeric(12, 8))
    error: Mapped[str | None] = mapped_column(Text)
