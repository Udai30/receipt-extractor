__all__ = ["AppServices", "build_app", "launch_options"]

logger = logging.getLogger(__name__)

TITLE: Final = "Receipt → JSON: OCR + LLM vs a vision LLM"
INTRO: Final = (
    "A receipt photo goes in; validated JSON (line items, prices, totals) comes out. "
    "Two pipelines are benchmarked on CORD-v2 for accuracy, latency and cost."
)
PRIVACY: Final = "Your image is processed in memory and not stored. It is not sent to Gemini."
QUEUE: Final = {"default_concurrency_limit": 2, "max_size": 20}
CACHE_SWEEP: Final = (300, 300)  # delete Gradio temp files older than 5 min, every 5 min
PAUSED_BANNER: Final = "⏸ Live calls are paused for today — sample receipts show cached results."
ABOUT: Final = (
    "**Pipelines.** A: RapidOCR (CPU) → Groq `gpt-oss-20b` → `Receipt` JSON, with up to two "
    "re-asks and an arithmetic check. B: the image → Gemini Flash-Lite (vision) → the same "
    "schema.\n\n"
    f"**Privacy.** {PRIVACY} Uploads are only ever read by pipeline A; Gemini's free tier sees "
    "public CORD images only.\n\n"
    "**Data.** Sample receipts: CORD-v2 (`naver-clova-ix/cord-v2`), CC-BY-4.0, Clova AI "
    "Research. Numbers come from `reports/`, generated by the benchmark's eval runs; nothing on "
    "this page is typed by hand."
)


@dataclass
class AppServices:
    reports_dir: Path
    live: LiveService
    showcase: Showcase | None
    assets_dir: Path = SHOWCASE_DIR


def _upload_roots() -> list[Path]:
    roots = [Path(tempfile.gettempdir()).resolve()]
    if custom := os.environ.get("GRADIO_TEMP_DIR"):
        roots.append(Path(custom).resolve())
    return roots


def consume_upload(path: str | os.PathLike[str]) -> bytes:
    """Read Gradio's temp copy of an upload into memory and delete it (only inside temp dirs)."""
    file = Path(path).resolve()
    if not any(file.is_relative_to(root) for root in _upload_roots()):
        raise ValueError("unexpected upload location")
    try:
        if file.stat().st_size > MAX_UPLOAD_BYTES:
            return b"\0" * (MAX_UPLOAD_BYTES + 1)  # rejected by the size check, never decoded
        return file.read_bytes()
    finally:
        file.unlink(missing_ok=True)


def _flatten(out: TryItOutput) -> list[Any]:
    return [out.banner, out.image, *out.a, *out.b]


def build_app(services: AppServices) -> Any:
    with gr.Blocks(
        title="Receipt extractor", analytics_enabled=False, delete_cache=CACHE_SWEEP
    ) as demo:
        gr.Markdown(f"# {TITLE}\n{INTRO}")
        with gr.Tabs():
            with gr.Tab("Results", id="results"):
                _results_tab(services)
            with gr.Tab("Try it", id="try"):
                _try_it_tab(services)
            with gr.Tab("Failures", id="failures"):
                _failures_tab(services)
            with gr.Tab("About", id="about"):
                gr.Markdown(ABOUT)
    demo.queue(**QUEUE)
    return demo


def _results_tab(services: AppServices) -> None:
    results = load_results(services.reports_dir)
    gr.Markdown(f"### {results.headline}")
    gr.Dataframe(
        value=results.rows,
        headers=list(results.columns),
        interactive=False,
        wrap=True,
        label="Results (CORD-v2; from reports/results.csv)",
    )
    gr.Markdown(results.note)
    with gr.Row():
        for path, alt in results.charts:
            gr.Image(value=str(path), label=alt, alt_text=alt, interactive=False, buttons=[])


def _pipeline_column(name: str) -> list[Any]:
    with gr.Group():
        title = gr.Markdown(f"### {name}")
        badge = gr.Markdown(elem_classes="badge")
        items = gr.Dataframe(
            headers=list(ITEM_COLUMNS), interactive=False, wrap=True, label="Line items"
        )
        totals = gr.Dataframe(headers=["Field", "Amount"], interactive=False, label="Totals")
        meta = gr.Markdown(elem_classes="metadata")
        with gr.Accordion("Evidence", open=False):
            raw = gr.Code(label="JSON (or the invalid reply)", language="json")
            ocr = gr.Textbox(label="OCR text (pipeline A)", lines=6)
    return [title, badge, items, totals, meta, raw, ocr]


def _try_it_tab(services: AppServices) -> None:
    paused = services.live.budget.paused
    banner = gr.Markdown(PAUSED_BANNER if paused else "", elem_classes="banner")
    with gr.Row():
        with gr.Column(scale=1, min_width=300):
            # No share/download buttons: "share" posts to the Hub, and uploads stay private.
            upload = gr.Image(
                type="filepath",
                sources=["upload"],
                label="Upload a receipt photo",
                height=320,
                buttons=[],
            )
            gr.Markdown(PRIVACY)
            run = gr.Button("Extract (pipeline A, live)", variant="primary")
            sample = gr.Radio(
                choices=sample_choices(services.showcase),
                label="…or pick a sample receipt (cached A and B results)",
            )
            sample_image = gr.Image(
                label="Sample receipt",
                interactive=False,
                height=320,
                alt_text="The selected CORD sample receipt",
                buttons=["fullscreen"],
            )
        with gr.Column(scale=2, min_width=300):
            columns = [*_pipeline_column("A"), *_pipeline_column("B")]
    outputs = [banner, sample_image, *columns]

    def on_sample(case_id: str | None) -> list[Any]:
        return _flatten(present_sample(services.showcase, case_id, assets=services.assets_dir))

    async def on_upload(
        path: str | None,
        progress: Any = gr.Progress(),  # noqa: B008 - Gradio injects progress this way
    ) -> list[Any]:
        if not path:
            return _flatten(present_sample(None, None))
        progress(0.1, desc="Running OCR and calling the model…")
        try:
            data = consume_upload(path)
        except (OSError, ValueError):
            data = b""
        return _flatten(present_live(await services.live.extract(data)))

    sample.change(on_sample, sample, outputs, api_name="sample")
    run.click(on_upload, upload, outputs, api_name="extract", concurrency_limit=2)


def _failures_tab(services: AppServices) -> None:
    failures = load_failures(services.reports_dir)
    gr.Markdown(failures.note or "Failures from the test runs, labelled by cause.")
    with gr.Row():
        cause = gr.Dropdown(failures.causes, value=ALL, label="Cause")
        pipeline = gr.Dropdown(failures.pipelines, value=ALL, label="Pipeline")
    table = gr.Dataframe(
        value=failures.rows,
        headers=list(failures.columns),
        interactive=False,
        wrap=True,
        label="Failures (reports/failures.csv)",
    )
    with gr.Row():
        gold = gr.Code(label="Gold", language="json")
        predicted = gr.Code(label="Predicted", language="json")

    def on_filter(c: str, p: str) -> list[list[str]]:
        return filter_failures(failures, c, p)

    def on_select(c: str, p: str, evt: gr.SelectData) -> tuple[str, str]:
        rows = filter_failures(failures, c, p)
        index = evt.index[0] if isinstance(evt.index, list | tuple) else evt.index
        return failure_detail(services.reports_dir, rows, index)

    cause.change(on_filter, [cause, pipeline], table, api_name="filter_failures")
    pipeline.change(on_filter, [cause, pipeline], table)
    table.select(on_select, [cause, pipeline], [gold, predicted])


def launch_options() -> dict[str, Any]:
    return {"theme": build_theme(), "css": CSS, "max_file_size": "5mb", "footer_links": []}
